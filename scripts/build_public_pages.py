def shorten(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    cut = text[: limit - 1].rsplit(" ", 1)[0].rstrip(" ,;:")
    return cut + "…"


def render_static_item(item: Mapping[str, Any], *, show_area: bool = True, show_deadline: bool = False) -> str:
    title = escape(clean_text(item.get("title_en")))
    meta = [
        clean_text(item.get("published_at")),
        source_display_name(item.get("source_name")),
        clean_text(item.get("area")) if show_area else "",
        clean_text(item.get("stage")),
    ]
    meta_html = " · ".join(escape(part) for part in meta if part)
    lines = ['        <li class="static-latest-item">']
    url = safe_http_url(item.get("source_url"))
    if url:
        lines.append(
            f'          <a class="static-latest-title" href="{escape(url)}" '
            f'target="_blank" rel="noopener noreferrer">{title}</a>'
        )
    else:
        lines.append(f'          <span class="static-latest-title">{title}</span>')
    if meta_html:
        lines.append(f'          <span class="static-latest-meta">{meta_html}</span>')
    if show_deadline:
        deadline = comment_deadline_display(item.get("comment_deadline"))
        if deadline:
            lines.append(f'          <span class="static-latest-deadline">Comments due: {escape(deadline)}</span>')
    # Rule-based previews are the same template sentence on every item, so
    # only an AI summary adds anything worth showing here.
    if summary_is_ai(item):
        summary = escape(shorten(clean_text(item.get("summary_en")), SUMMARY_MAX_CHARS))
        lines.append(f'          <p class="static-latest-summary">{summary} <em>(AI summary)</em></p>')
    lines.append("        </li>")
    return "\n".join(lines)


def render_item_list(items: Sequence[Mapping[str, Any]], **options: bool) -> str:
    body = "\n".join(render_static_item(item, **options) for item in items)
    return f'        <ol class="static-latest-list">\n{body}\n        </ol>'


def render_static_latest(items: Sequence[Mapping[str, Any]], updated: date | None) -> str:
    heading_note = f" — checked {updated.isoformat()}" if updated else ""
    return (
        f"{STATIC_START}\n"
        '      <section class="static-latest" aria-labelledby="static-latest-title">\n'
        f'        <h2 id="static-latest-title">Latest Japan legal &amp; regulatory updates{heading_note}</h2>\n'
        '        <p class="static-latest-note">Newest official publications from the Japanese sources this '
        "dashboard monitors. Titles and AI summaries are unofficial English monitoring aids, not legal "
        "advice; each link opens the original Japanese official source, which remains authoritative.</p>\n"
        f"{render_item_list(items)}\n"
        "      </section>\n"
        f"      {STATIC_END}"
    )


def render_area_links(prefix: str, current: str = "") -> str:
    """Links to every area page plus the public-comments page.

    ``prefix`` is the relative path from the page being written to the site
    root, so the links work on the live site and in a local preview alike.
    """
    links = []
    for page in AREA_PAGES:
        label = escape(CHANNEL_BY_VALUE[page.channel].label)
        if page.slug == current:
            links.append(f'<li><span aria-current="page">{label}</span></li>')
        else:
            links.append(f'<li><a href="{prefix}{area_page_path(page)}">{label}</a></li>')
    if current == PUBLIC_COMMENTS_DIR_NAME:
        links.append('<li><span aria-current="page">Open public comments</span></li>')
    else:
        links.append(f'<li><a href="{prefix}{PUBLIC_COMMENTS_DIR_NAME}/">Open public comments</a></li>')
    return "\n".join("          " + link for link in links)


