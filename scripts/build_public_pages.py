def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    write_text_atomic(path, text)
    return True


def build(
    data_path: Path,
    index_path: Path,
    sitemap_path: Path,
    today: date,
    site_dir: Path | None = None,
    raw_path: Path | None = None,
    explainers_dir: Path | None = None,
) -> dict[str, Any]:
    site_dir = site_dir or index_path.parent
    items = load_items(data_path)
    index = ex.OfficialIndex.build(load_items(raw_path)) if raw_path is not None and raw_path.exists() else None
    dossiers = index.timeline if index else {}
    explained: dict[str, ex.Published] = {}
    reports: dict[str, ex.Report] = {}
    if index is not None and explainers_dir is not None:
        explained, reports = ex.published_by_item(ex.load_explainers(explainers_dir), index, today)
    locale_bundles = el.load_locales(explainers_dir.parent / "explainer_locales") if explainers_dir else {}
    updated = latest_checked(items)

    html = index_path.read_text(encoding="utf-8")
    html = replace_static_block(html, render_static_latest(latest_items(items, today, STATIC_LATEST_COUNT), updated))
    html = replace_block(html, AREA_NAV_START, AREA_NAV_END, render_area_nav())
    changed = {"index": write_if_changed(index_path, html)}

    sitemap_entries: list[tuple[str, date | None]] = [(SITE_URL, updated)]
    for page in AREA_PAGES:
        path = area_page_path(page)
        changed[path] = write_if_changed(site_dir / path / "index.html", render_area_page(page, items, today))
        sitemap_entries.append((SITE_URL + path, latest_checked(area_items(items, page))))
    path = f"{PUBLIC_COMMENTS_DIR_NAME}/"
    changed[path] = write_if_changed(site_dir / path / "index.html", render_public_comments_page(items, today))
    sitemap_entries.append((SITE_URL + path, updated))
    sitemap_entries += [(SITE_URL + path, None) for path in STATIC_SITEMAP_PATHS]

    with_pages = page_items(items)
    page_ids = {item_page_id(item) for item in with_pages}
    item_pages_changed = 0
    timeline_pages = 0
    explainer_pages = 0
    localized_pages = 0
    for item in with_pages:
        path = item_page_path(item)
        dossier = dossiers.get(item_page_id(item))
        explainer = explained.get(item_page_id(item))
        timeline_pages += dossier is not None
        explainer_pages += explainer is not None
        bundle = locale_bundles.get(explainer.dossier_id, {}) if explainer else {}
        local_entries = {
            lang: translated for lang in el.LOCALES
            if explainer is not None
            for translated in [el.localized_entry(explainer, bundle, lang)]
            if translated is not None
        }
        item_pages_changed += write_if_changed(
            site_dir / path / "index.html",
            render_item_page(
                item, dossier, page_ids, explainer,
                index.page_status(item_page_id(item)) if explainer is not None and index else None,
                available_locales=tuple(local_entries),
            ),
        )
        for lang in el.LOCALES:
            if lang not in local_entries:
                stale = site_dir / path / el.URL_SLUGS[lang]
                if stale.is_dir() and sorted(p.name for p in stale.iterdir()) == ["index.html"]:
                    (stale / "index.html").unlink()
                    stale.rmdir()
        for lang, translated in local_entries.items():
            local_path = path + el.URL_SLUGS[lang] + "/"
            item_pages_changed += write_if_changed(
                site_dir / local_path / "index.html",
                render_item_page(item, dossier, page_ids, translated,
                                 index.page_status(item_page_id(item)) if index else None,
                                 locale=lang, available_locales=tuple(local_entries)),
            )
            localized_pages += 1
            sitemap_entries.append((SITE_URL + local_path, item_lastmod(item, dossier, explainer)))
        if item_is_indexable(item, explainer):
            sitemap_entries.append((SITE_URL + path, item_lastmod(item, dossier, explainer)))
    removed = prune_item_pages(site_dir / ITEM_DIR_NAME, {item_page_id(item) for item in with_pages})
    changed["sitemap"] = write_if_changed(sitemap_path, render_sitemap(sitemap_entries))

    return {
        "pages_written": len(AREA_PAGES) + 1,
        "item_pages": len(with_pages),
        "item_pages_indexable": sum(
            1 for item in with_pages if item_is_indexable(item, explained.get(item_page_id(item)))
        ),
        "item_pages_changed": item_pages_changed,
        "item_pages_removed": removed,
        "item_pages_with_timeline": timeline_pages,
        "item_pages_with_explainer": explainer_pages,
        "localized_explainer_pages": localized_pages,
        "explainers": {
            "files": len(reports),
            "published": len({entry.dossier_id for entry in explained.values()}),
            "withheld_with_errors": sorted(d for d, r in reports.items() if not r.ok),
            "policy": ex.publish_policy(),
        },
        "timelines": summarize_timelines(dossiers),
        "files_changed": sorted(name for name, was_changed in changed.items() if was_changed),
    }


def prune_item_pages(item_dir: Path, keep: set[str]) -> int:
    """Remove the pages of items that are no longer published.

    Only a directory this script could have written -- a safe-id name holding
    nothing but ``index.html`` -- is removed; anything else is left alone.
    """
    if not item_dir.is_dir():
        return 0
    removed = 0
    for child in sorted(item_dir.iterdir()):
        if not child.is_dir() or child.name in keep or not ITEM_ID_PATTERN.match(child.name):
            continue
        contents = list(child.iterdir())
        allowed = {"index.html", *el.URL_SLUGS.values()}
        if not contents or any(p.name not in allowed for p in contents):
            continue
        locales = [p for p in contents if p.is_dir()]
        if any(p.name not in el.URL_SLUGS.values()
               or sorted(q.name for q in p.iterdir()) != ["index.html"]
               or not (p / "index.html").is_file() for p in locales):
            continue
        files = [p for p in contents if p.is_file()]
        if any(p.name != "index.html" for p in files) or len(files) != 1:
            continue
        for p in locales:
            (p / "index.html").unlink()
            p.rmdir()
        files[0].unlink()
        child.rmdir()
        removed += 1
    return removed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", type=Path, default=DATA_PATH)
    parser.add_argument("--index", type=Path, default=INDEX_PATH)
    parser.add_argument("--sitemap", type=Path, default=SITEMAP_PATH)
    parser.add_argument("--raw", type=Path, default=RAW_PATH, help="raw history for item timelines")
    parser.add_argument(
        "--explainers", type=Path, default=ex.EXPLAINERS_DIR, help="hand-written reform explainers"
    )
    parser.add_argument("--today", type=date.fromisoformat, default=None, help="JST date (YYYY-MM-DD)")
    args = parser.parse_args(argv)
    today = args.today or datetime.now(JST).date()
    print(json.dumps(build(args.data, args.index, args.sitemap, today, raw_path=args.raw, explainers_dir=args.explainers), sort_keys=True))
    return 0


