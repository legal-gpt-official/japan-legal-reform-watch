def replace_block(html: str, start_marker: str, end_marker: str, block: str) -> str:
    start = html.find(start_marker)
    end = html.find(end_marker)
    if start < 0 or end < start or html.count(start_marker) != 1 or html.count(end_marker) != 1:
        raise ValueError(f"index.html must contain exactly one {start_marker[:20]}... marker pair")
    return html[:start] + block + html[end + len(end_marker):]


def replace_static_block(html: str, block: str) -> str:
    return replace_block(html, STATIC_START, STATIC_END, block)


def json_ld(data: Mapping[str, Any]) -> str:
    # "</" cannot close the script element when escaped as "<\/".
    return json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")


