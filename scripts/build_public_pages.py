"""Build the crawlable parts of the public site from the published data.

The dashboard renders its cards in the browser from JSON, so a crawler that
does not run JavaScript sees an empty page. This stage writes:

* a static list of the latest updates into ``docs/index.html`` between the
  ``STATIC-LATEST`` markers, inside the cards container -- ``app.js`` replaces
  it with the interactive cards as soon as the data loads, so visitors and
  crawlers are shown the same records;
* a "Browse by area" navigation into ``docs/index.html`` between the
  ``AREA-NAV`` markers;
* one static landing page per monitoring area under ``docs/areas/<slug>/``
  and a cross-area page of open public comments under
  ``docs/public-comments/``;
* one static page per published item under ``docs/u/<id>/`` -- only an
  item with an AI summary is indexable; a rule-based item's page is
  ``noindex`` because its body would be the template every such item shares;
* ``docs/sitemap.xml`` listing the indexable pages.

An item page also shows a factual timeline of related official records
(``law_timeline.py``: the same instrument, the bill it came from, the public
comment on its draft) built from ``data/raw_items.json``, and, when one is
published for the reform, the hand-written explainer from
``data/explainers/`` (``explainers.py``: Background, History, What's Next,
Business Impact). An item page with a published explainer is indexable even
when its own summary is rule-based.

It reads ``docs/data/legal_updates.json``, ``data/raw_items.json`` and
``data/explainers/`` and changes none of them.
Output is deterministic for a given input and JST date (no wall-clock
timestamps), so an unchanged corpus produces no diff. Every record field is
untrusted: text is HTML/XML-escaped and only http(s) source URLs are emitted
as links.
"""

