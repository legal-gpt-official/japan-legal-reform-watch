def render_area_page(page: AreaPage, items: Sequence[Mapping[str, Any]], today: date) -> str:
    channel = CHANNEL_BY_VALUE[page.channel]
    in_area = area_items(items, page)
    updated = latest_checked(in_area)
    open_items = open_comments(in_area, today)
    latest = latest_items(in_area, today, AREA_LATEST_COUNT)
    ai_count = sum(1 for item in in_area if summary_is_ai(item))
    description = (
        f"English monitoring of Japanese {page.topics}: the latest official updates, open public "
        "comments and deadlines, and their original Japanese sources. Updated daily; not legal advice."
    )
    stats = [f"{len(in_area):,} updates tracked", f"{ai_count:,} with AI summaries",
             f"{len(open_items):,} open public comments"]
    if updated:
        stats.append(f"last checked {updated.isoformat()}")

    parts = [
        f'    <p class="area-page-intro">Official Japanese developments on {escape(page.topics)}, '
        "monitored daily from government, regulator, Diet, and self-regulatory sources and labelled in "
        f"English for triage. {escape(AREA_LABEL_NOTICE)}</p>",
        f'    <p class="area-page-stats">{escape(" · ".join(stats))}</p>',
        '    <p class="area-page-actions">',
        f'      <a class="area-page-action" href="{escape(dashboard_area_url(page))}">Search and filter this area in the dashboard</a>',
        f'      <a class="area-page-action" href="../../feeds/{channel.value}.xml">RSS feed</a>',
        f'      <a class="area-page-action" href="../../feeds/{channel.value}.ics">Deadline calendar (.ics)</a>',
        "    </p>",
    ]
    if open_items:
        parts += [
            '    <section class="area-page-section" aria-labelledby="open-comments-title">',
            '      <h2 id="open-comments-title">Open public comments</h2>',
            '      <p class="static-latest-note">Consultations still accepting comments, soonest deadline first. '
            "Confirm the deadline and submission method in the official source.</p>",
            render_item_list(open_items[:AREA_OPEN_COMMENTS_COUNT], show_area=False, show_deadline=True),
            "    </section>",
        ]
    parts += [
        '    <section class="area-page-section" aria-labelledby="latest-title">',
        '      <h2 id="latest-title">Latest updates</h2>',
        '      <p class="static-latest-note">Newest official publications first.</p>',
        render_item_list(latest, show_area=False) if latest else '      <p>No dated updates yet.</p>',
        "    </section>",
    ]
    sources = top_sources(in_area, AREA_TOP_SOURCES)
    if sources:
        rows = "\n".join(f"        <li>{escape(name)} ({count:,})</li>" for name, count in sources)
        parts += [
            '    <section class="area-page-section" aria-labelledby="sources-title">',
            '      <h2 id="sources-title">Most frequent sources in this area</h2>',
            f'      <ul class="area-page-sources">\n{rows}\n      </ul>',
            "    </section>",
        ]
    return render_page(
        path=area_page_path(page),
        title=f"{page.heading} — Japan Legal Reform Watch",
        description=description,
        heading=page.heading,
        breadcrumb=channel.label,
        body="\n".join(parts),
        current=page.slug,
    )


