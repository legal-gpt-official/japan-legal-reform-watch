def render_page_status(status: Mapping[str, Any], locale: str = "en") -> str:
    """One line on the legal status of this page's own instrument, from its e-Gov records.

    The explainer describes the whole reform; an amending ordinance on one page
    can still be partly pending when the Act on another is in force. Translated
    pages need the line as much as the English one, so it is localized too.
    """
    ui = PAGE_STATUS_UI.get(locale)
    if ui:
        pieces = [f"{status['instrument']}（{status['number']}）"]
        if status.get("target"):
            pieces.append(ui["amending"].format(target=status["target"]))
        if status.get("promulgated"):
            pieces.append(ui["promulgated"].format(date=status["promulgated"].isoformat()))
        if status.get("effective_dates"):
            pieces.append(ui["effective"].format(
                dates="、".join(d.isoformat() for d in status["effective_dates"])))
        if status.get("pending"):
            pieces.append(ui["pending"])
        return f"{ui['lead']}：" + "；".join(pieces) + "。"
    pieces = [f"{status['instrument']} ({status['number']})"]
    if status.get("target"):
        pieces.append(f"amending {status['target']}")
    facts = []
    if status.get("promulgated"):
        facts.append(f"promulgated {status['promulgated'].isoformat()}")
    if status.get("effective_dates"):
        facts.append("effective date(s) recorded by e-Gov: " + ", ".join(d.isoformat() for d in status["effective_dates"]))
    if status.get("pending"):
        facts.append("at least one effective date not yet fixed (to be set by Cabinet Order)")
    return "This page's record: " + ", ".join(pieces) + (" — " + "; ".join(facts) if facts else "") + "."


def render_explainer(entry: "ex.Published", page_status: Mapping[str, Any] | None = None, locale: str = "en") -> list[str]:
    """The explainer sections the review policy allows. Every value is escaped; links pass ``safe_http_url``.

    All sections are ``<details open>`` so the full text is in the static
    HTML and readable without JavaScript; a reader may fold any of them.
    Categories held back by the review policy are left out and named.
    """
    visible = entry.visible
    data = entry.data
    ui = EXPLAINER_UI.get(locale, EXPLAINER_UI['en'])
    sources = [s for s in data.get("official_sources") or [] if isinstance(s, Mapping)]
    numbers = {s.get("id"): n for n, s in enumerate(sources, start=1)}
    stage = ex.STAGE_LABELS.get(str(data.get("current_stage")), "")
    instrument = INSTRUMENT_TYPE_LABELS.get(str(data.get("instrument_type")), "")
    verified = clean_text(data.get("verified_at"))
    meta = " · ".join(
        part
        for part in (
            f"{ui['current_stage']}: {stage}" if stage else "",
            f"{ui['instrument']}: {instrument}" if instrument else "",
            f"{ui['verified']}: {verified}" if verified else "",
        )
        if part
    )
    parts = [
        '    <section class="area-page-section explainer" aria-labelledby="explainer-title">',
        f'      <p class="explainer-kicker">{escape(ui["kicker"])}</p>',
        f'      <h2 id="explainer-title">{escape(clean_text(data.get("title_en")))}</h2>',
        f'      <p class="explainer-meta">{escape(meta)}</p>',
        f'      <p class="static-latest-note">{escape(EXPLAINER_NOTICE if locale == "en" else ui["official"])}</p>',
    ]
    named = [
        f"{clean_text(i.get('name_en'))} ({clean_text(i.get('name_ja'))}, {clean_text(i.get('number'))})"
        for i in data.get("instruments") or []
        if isinstance(i, Mapping) and clean_text(i.get("number"))
    ]
    if named:
        parts.append(
            f'      <p class="explainer-refs">{escape(ui["instruments"])} (English names are unofficial descriptions): '
            f'{escape("; ".join(named))}</p>'
        )
    if page_status:
        parts.append(f'      <p class="explainer-meta">{escape(render_page_status(page_status, locale))}</p>')
    for notice in entry.report.notices:
        parts.append(f'      <p class="explainer-alert" role="note">{escape(notice)}</p>')
    held = [CATEGORY_LABELS[c] for c in ex.CATEGORIES if c not in visible]
    if held:
        parts.append(
            '      <p class="explainer-refs">Not shown until reviewed: ' + escape(", ".join(held)) + ".</p>"
        )
    quick_take = data.get("quick_take")
    if isinstance(quick_take, Mapping):
        cards = []
        for key, heading, category, ids in (
            ("what_changed", ui["changed"], "facts", (data.get("background") or {}).get("source_ids")),
            ("who_is_affected", ui["affected"], "assessment", (data.get("business_impact") or {}).get("source_ids")),
            ("what_to_do_now", ui["do"], "assessment",
             (data.get("business_impact") or {}).get("source_ids")),
        ):
            if category not in visible or not clean_text(quick_take.get(key)):
                continue
            citation = _source_refs(ids, numbers)
            refs = f' <span class="explainer-quick-refs">{citation}</span>' if citation else ""
            cards.append(
                '        <div class="explainer-quick-card">'
                f'<h3>{heading}</h3><p>{escape(clean_text(quick_take[key]))}{refs}</p></div>'
            )
        if cards:
            parts.append('      <section class="explainer-quick" aria-label="At a glance">')
            parts.append(f'        <h3 class="explainer-quick-title">{escape(ui["glance"])}</h3>')
            parts += cards
            parts.append("      </section>")
    show_next = "outlook" in visible or "procedure" in visible
    nav = [("explainer-background", ui["background"]), ("explainer-history", ui["nav_history"])]
    nav += [("explainer-next", ui["nav_next"])] if show_next else []
    nav += [("explainer-impact", ui["nav_impact"])] if "assessment" in visible else []
    parts.append('      <nav class="explainer-nav" aria-label="Explainer sections">')
    parts += [f'        <a href="#{anchor}">{escape(label)}</a>' for anchor, label in nav]
    parts.append("      </nav>")

    def section(anchor: str, heading: str, body: list[str], refs: str = "") -> None:
        parts.append(f'      <details class="explainer-section" id="{anchor}" open>')
        parts.append(f"        <summary><h3>{heading}</h3></summary>")
        parts.extend(body)
        if refs:
            parts.append(f'        <p class="explainer-refs">Sources: {refs}</p>')
        parts.append("      </details>")

    background = data.get("background") or {}
    section(
        "explainer-background",
        escape(ui["background"]),
        _paragraphs(background.get("paragraphs")),
        _source_refs(background.get("source_ids"), numbers),
    )

    history = data.get("history") or {}
    body = _paragraphs(history.get("paragraphs"))
    dated = []
    for row in data.get("key_dates") or []:
        if not isinstance(row, Mapping):
            continue
        when = strict_iso_date(row.get("date"))
        if when:
            dated.append((when, clean_text(row.get("label")), _source_refs(row.get("source_ids"), numbers)))
    if dated:
        body.append('        <ol class="explainer-dates">')
        for when, label, refs in sorted(dated, key=lambda r: (r[0], r[1])):
            body.append(f"          <li><strong>{when.isoformat()}</strong> — {escape(label)} {refs}</li>")
        body.append("        </ol>")
    if locale == "en":  # translated pages carry no timeline for this sentence to point to
        body.append(
            '        <p class="explainer-refs">The timeline of related official records below lists the '
            "records this dashboard has matched.</p>"
        )
    section(
        "explainer-history",
        escape(ui["history"]),
        body,
        _source_refs(history.get("source_ids"), numbers),
    )

    steps = data.get("next_steps") or {}
    body = []
    if "outlook" in visible:
        body.append(f'        <h4>{escape(ui["confirmed"])}</h4>')
    confirmed = [s for s in steps.get("confirmed") or [] if isinstance(s, Mapping) and clean_text(s.get("text"))]
    if "outlook" in visible and confirmed:
        body.append('        <ul class="explainer-list">')
        for step in confirmed:
            when = strict_iso_date(step.get("date"))
            lead = f"<strong>{when.isoformat()}</strong> — " if when else ""
            refs = _source_refs(step.get("source_ids"), numbers)
            body.append(f"          <li>{lead}{escape(clean_text(step.get('text')))} {refs}</li>")
        body.append("        </ul>")
    elif "outlook" in visible:
        body.append('        <p class="explainer-text">No further step has been confirmed by an official source.</p>')
    if steps.get("expected") and "procedure" in visible:
        body.append(f'        <h4>{escape(ui["expected"])}</h4>')
        body.append(
            '        <p class="explainer-refs">The usual procedure for this kind of instrument; not a '
            "forecast for this reform.</p>"
        )
        body += _bullets(steps.get("expected"))
    if "outlook" in visible:
        body.append(f'        <h4>{escape(ui["uncertainties"])}</h4>')
        body += _bullets(steps.get("uncertainties"))
    if show_next:
        section("explainer-next", escape(ui["next"]), body)

    if "assessment" in visible:
        impact = data.get("business_impact") or {}
        body = _paragraphs(impact.get("paragraphs"))
        if impact.get("checklist"):
            body.append(f'        <h4>{escape(ui["check"])}</h4>')
            body += _bullets(impact.get("checklist"))
        section(
            "explainer-impact",
            escape(ui["impact"]),
            body,
            _source_refs(impact.get("source_ids"), numbers),
        )

    parts.append(f'      <h3 class="explainer-sources-title">{escape(ui["sources"])}</h3>')
    parts.append('      <ol class="explainer-sources">')
    for n, source in enumerate(sources, start=1):
        title = escape(clean_text(source.get("title")))
        publisher = escape(clean_text(source.get("publisher")))
        accessed = escape(clean_text(source.get("accessed_at")))
        kind = "" if source.get("kind") == "primary" else " (secondary source)"
        url = safe_http_url(source.get("url"))
        name = f'<a href="{escape(url)}" target="_blank" rel="noopener noreferrer">{title}</a>' if url else title
        parts.append(f'        <li id="explainer-source-{n}">{name} — {publisher}{kind}; accessed {accessed}</li>')
    parts.append("      </ol>")
    parts.append("    </section>")
    return parts


def render_item_page(
    item: Mapping[str, Any],
    dossier: Dossier | None = None,
    page_ids: set[str] | None = None,
    explainer: "ex.Published | None" = None,
    page_status: Mapping[str, Any] | None = None,
    locale: str = "en",
    available_locales: Sequence[str] = (),
) -> str:
    """The standalone page for one published item.

    Shows only fields the dashboard card already shows, every one escaped,
    and the source link only when it passes ``safe_http_url``. A rule-based
    body is never shown -- it is the same template sentence on every such
    item -- so those pages carry only the metadata and are ``noindex``. No
    field that changes without the item changing (``last_checked``, the
    build date) is shown, so a quiet day rewrites no page.
    """
    translated = locale != "en" and explainer is not None
    title_en = clean_text(explainer.data.get("title_en") if translated else item.get("title_en"))
    title_ja = clean_text(item.get("title_ja"))
    path = item_page_path(item) + (el.URL_SLUGS[locale] + "/" if translated else "")
    prefix = "../" * len(path.rstrip("/").split("/"))
    alternates = {"en": item_page_path(item)}
    alternates.update({k: item_page_path(item) + el.URL_SLUGS[k] + "/" for k in available_locales})
    source = source_display_name(item.get("source_name"))
    area = clean_text(item.get("area"))
    stage = clean_text(item.get("stage"))
    ai = summary_is_ai(item)
    indexable = ai or explainer is not None
    area_page = AREA_PAGE_BY_AREA.get(area)
    area_label = CHANNEL_BY_VALUE[area_page.channel].label if area_page else ""

    published = strict_iso_date(item.get("published_at"))
    facts = [("Published", published.isoformat() if published else "not stated by the source")]
    impact = clean_text(item.get("impact_level"))
    facts += [
        (label, value)
        for label, value in (("Source", source), ("Stage", stage), ("Area", area), ("Impact (preliminary)", impact))
        if value
    ]
    deadline = comment_deadline_display(item.get("comment_deadline"))
    if deadline:
        facts.append(("Comment deadline", deadline))
    first_seen = strict_iso_date(item.get("first_seen_at"))
    if first_seen:
        facts.append(("First detected by this dashboard", first_seen.isoformat()))

    if translated:
        description = shorten(clean_text((explainer.data.get("quick_take") or {}).get("what_changed")),
                              ITEM_DESCRIPTION_MAX_CHARS)
    elif ai:
        description = shorten(clean_text(item.get("summary_en")), ITEM_DESCRIPTION_MAX_CHARS)
    elif explainer is not None:
        background = (explainer.data.get("background") or {}).get("paragraphs") or [""]
        description = shorten(clean_text(background[0]), ITEM_DESCRIPTION_MAX_CHARS)
    else:
        description = (
            "Unofficial English label for an official Japanese update"
            f"{' from ' + source if source else ''}, with a link to the original Japanese source."
        )

    parts = []
    if explainer is not None and locale == "en":
        parts.append('<p id="explainer-locale-fallback" class="explainer-alert" role="status" hidden></p>')
    if explainer is not None:
        labels = {"en": "English", "ja": "日本語", "zh-Hans": "简体中文"}
        switch_links = []
        for code in ("en", *available_locales):
            dest = item_page_path(item) + (el.URL_SLUGS[code] + "/" if code != "en" else "")
            marker = ' aria-current="page"' if code == locale else ""
            switch_links.append(f'<a href="{prefix}{dest}" lang="{code}"{marker}>{labels[code]}</a>')
        parts.append('<nav class="explainer-langs" aria-label="Language / 言語 / 语言">' +
                     " ".join(switch_links) + "</nav>")
    if title_ja and locale != "ja":
        parts.append(f'    <p class="area-page-intro" lang="ja">{escape(title_ja)}</p>')
    facts_text = " · ".join(f"{label}: {value}" for label, value in facts)
    parts.append(f'    <p class="area-page-stats">{escape(facts_text)}</p>')
    parts.append('    <p class="area-page-actions">')
    url = safe_http_url(item.get("source_url"))
    if url:
        parts.append(
            f'      <a class="area-page-action" href="{escape(url)}" target="_blank" '
            'rel="noopener noreferrer">View the original Japanese source</a>'
        )
    if area_page:
        parts.append(
            f'      <a class="area-page-action" href="{prefix}{area_page_path(area_page)}">'
            f"More {escape(area_label)} updates</a>"
        )
    parts.append(f'      <a class="area-page-action" href="{prefix}?lang={escape(locale)}">Search all updates in the dashboard</a>')
    parts.append("    </p>")

    if not translated:
        parts.append('    <section class="area-page-section" aria-labelledby="item-summary-title">')
    if ai and not translated:
        parts += [
            '      <h2 id="item-summary-title">AI summary</h2>',
            '      <p class="static-latest-note">Generated by AI from the Japanese source metadata. It is an '
            "unofficial monitoring aid, not legal advice, and may contain errors. The area, stage, and impact "
            "labels are preliminary keyword-based triage labels. Confirm every point in the original Japanese "
            "source.</p>",
        ]
        for heading, key in (
            ("Summary", "summary_en"),
            ("Business Impact", "business_impact_en"),
            ("Recommended Action", "recommended_action_en"),
        ):
            text = clean_text(item.get(key))
            if text:
                parts.append(f"      <h3>{heading}</h3>")
                parts.append(f'      <p class="area-page-intro">{escape(text)}</p>')
    elif not translated:
        parts += [
            '      <h2 id="item-summary-title">Summary</h2>',
            "      <p>An English AI summary is not yet available for this update. The English title is a "
            "rule-based label; please read the original Japanese source.</p>",
        ]
    if not translated:
        parts.append("    </section>")
    if explainer is not None:
        parts += render_explainer(explainer, page_status, locale)
    if dossier is not None and locale == "en":
        parts += render_timeline(item_page_id(item), dossier, page_ids or set())

    return render_page(
        path=path,
        title=f"{title_en} — Japan Legal Reform Watch",
        description=description,
        heading=title_en,
        breadcrumb=shorten(title_en, 60),
        body="\n".join(parts),
        current="",
        page_type="WebPage",
        parent=(area_label, area_page_path(area_page)) if area_page else None,
        indexable=indexable,
        area_nav=False,
        lang=locale,
        alternates=alternates if explainer is not None else None,
    )


def render_sitemap(entries: Sequence[tuple[str, date | None]]) -> str:
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for loc, lastmod in entries:
        lines.append("  <url>")
        lines.append(f"    <loc>{xml_escape(loc)}</loc>")
        if lastmod:
            lines.append(f"    <lastmod>{lastmod.isoformat()}</lastmod>")
        lines.append("  </url>")
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


